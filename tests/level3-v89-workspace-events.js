/* UI persistence regression for Level 3: real workspace event handlers. */
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const listeners={},saved={};
const storage={getItem:key=>saved[key]||null,setItem:(key,value)=>{saved[key]=value}};
const document={addEventListener:(type,fn)=>{listeners[type]=fn},getElementById:()=>null,querySelectorAll:()=>[]};
const window={BAContent:{},scrollTo(){},scrollY:0};
const ctx={window,document,localStorage:storage,htmlEscape:String,catalog:Array.from({length:26},(_,i)=>'Course '+i),coursePlans:Array.from({length:26},()=>({hours:100})),data:{},go(){},draw(){},console};
vm.createContext(ctx);
for(const name of ['core.js','level3.js','level3-advanced-v73.js','level3-corporate-depth-v74.js','level3-integrated-v75.js','level3-board-decisions-v76.js','level3-cumulative-v77.js','level3-mastery-v78.js','level3-final-depth-v79.js','level3-executive-labs-v80.js','level3-executive-synthesis-v81.js','level3-independent-transfer-v83.js','level3-historical-cases-v84.js','level3-historical-evidence-v85.js','level3-integrated-final-v87.js','workspace-v40.js'])vm.runInContext(fs.readFileSync('learning/'+name,'utf8'),ctx,{filename:name});
const click=dataset=>listeners.click({target:{closest:()=>({dataset})}});
const change=(dataset,value,checked)=>listeners.change({target:{dataset,value,checked}});
const input=(dataset,value)=>listeners.input({target:{dataset,value}});
click({learnCourse:'course-20'});
const key=window.BALearning.KEY,draft='sectionExam-l3-v87-integrated-exam',longText='Financial analysis. '.repeat(1000);
input({learnDraft:draft},longText);
assert.equal(JSON.parse(saved[key]).courses['course-20'].drafts[draft],longText);
change({learnReview:draft+':0'},'4');
input({learnDraft:draft},longText+' Updated.');
const s=JSON.parse(saved[key]).courses['course-20'];
assert.equal(s.reviews[draft],undefined,'Writing edits must invalidate stale review');
const lesson=window.BAContent['course-20'].modules[0].lessons[0].id;
change({learnLesson:lesson},'on',true);
assert.ok(JSON.parse(saved[key]).courses['course-20'].lessons.includes(lesson));
change({learnLesson:lesson},'on',false);
assert.ok(!JSON.parse(saved[key]).courses['course-20'].lessons.includes(lesson));
const exam=window.BAContent['course-20'].sectionExams.find(e=>e.id==='l3-v87-integrated-exam'),kind='sectionExam-'+exam.id;
for(const q of exam.questions)change({learnAnswer:kind+':'+q.id},String(q.correct));
click({learnGrade:kind});
assert.equal(JSON.parse(saved[key]).courses['course-20'].attempts.at(-1).score,100);
click({learnRetry:kind});
const reloaded=window.BALearning.load(storage).courses['course-20'];
assert.equal(reloaded.drafts[draft],longText+' Updated.');
assert.equal(reloaded.attempts.at(-1).score,100);
assert.equal(reloaded.feedback[kind],false);
assert.equal(Object.keys(reloaded.answers[kind]).length,0);
console.log('Level 3 workspace input, save, review invalidation, lesson toggles and final retakes passed.');
