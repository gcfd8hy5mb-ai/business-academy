/* Level 3 v88 end-to-end learning state: two finals, drafts, local restore, retakes and mastery separation. */
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx={window:{BAContent:{}},module:{exports:{}}};vm.createContext(ctx);
for(const file of ['core.js','level3.js','level3-advanced-v73.js','level3-corporate-depth-v74.js','level3-integrated-v75.js','level3-board-decisions-v76.js','level3-cumulative-v77.js','level3-mastery-v78.js','level3-final-depth-v79.js','level3-executive-labs-v80.js','level3-executive-synthesis-v81.js','level3-independent-transfer-v83.js','level3-historical-cases-v84.js','level3-historical-evidence-v85.js','level3-integrated-final-v87.js'])
 vm.runInContext(fs.readFileSync('learning/'+file,'utf8'),ctx,{filename:file});
const L=ctx.window.BALearning,c=ctx.window.BAContent['course-20'];c.id='course-20';
const original=c.sectionExams.find(x=>x.id==='l3-final-v77-exam'),second=c.sectionExams.find(x=>x.id==='l3-v87-integrated-exam');
assert.ok(original&&second&&original.questions.length===16&&second.questions.length===7);
const store=L.empty(),s=L.state(store,c.id);
const k1='sectionExam-'+original.id,k2='sectionExam-'+second.id;
s.answers[k1]={};original.questions.forEach(q=>{s.answers[k1][q.id]=q.correct});
s.answers[k2]={};second.questions.slice(0,-1).forEach(q=>{s.answers[k2][q.id]=q.correct});
assert.equal(L.grade(store,c,k2),false,'Incomplete final must not record an attempt');
assert.equal(s.attempts.length,0);
const first=L.grade(store,c,k1);assert.equal(first.score,100);
assert.equal(L.latest(s,k1).score,100);
assert.equal(L.latest(s,k2),undefined,'Second final must be separate');
second.questions.at(-1).correct>=0&&(s.answers[k2][second.questions.at(-1).id]=second.questions.at(-1).correct);
const secondPassed=L.grade(store,c,k2);assert.equal(secondPassed.score,100);
assert.equal(L.latest(s,k1).score,100,'Second sitting may not overwrite original final');
assert.equal(L.latest(s,k2).score,100);
const firstQuestion=second.questions[0],correct=firstQuestion.correct;
s.answers[k2][firstQuestion.id]=(correct+1)%4;
const retake=L.grade(store,c,k2);assert.ok(retake.score<100);
assert.equal(secondPassed.answers[firstQuestion.id],correct,'Earlier attempt snapshot must be immutable');
assert.equal(L.latest(s,k2).score,retake.score);
assert.equal(L.latest(s,k1).score,100,'Retake cannot modify original final');
s.drafts[k1]='Original board analysis with assumptions';
s.drafts[k2]='Separate second-sitting board analysis';
s.reviews[k1]=original.rubric.map(()=>4);
s.reviews[k2]=second.rubric.map(()=>3);
assert.equal(L.reviewed(s,k1,original.rubric),true);
assert.equal(L.reviewed(s,k2,second.rubric),true);
const serialized=JSON.stringify(store);
const local={getItem(key){return key===L.KEY?serialized:null;}};
const restored=L.load(local),rs=L.state(restored,c.id);
assert.equal(rs.drafts[k1],s.drafts[k1]);assert.equal(rs.drafts[k2],s.drafts[k2]);
assert.equal(L.latest(rs,k1).score,100);assert.equal(L.latest(rs,k2).score,retake.score);
assert.equal(L.mastery(restored,c).mastered,false,'Answer submissions alone cannot meet the full learning mastery gates');
assert.ok(fs.readFileSync('learning/workspace-v40.js','utf8').includes('l3-v87-integrated-exam'));
console.log('Level 3 v88 two-final persistence, retries, draft separation and mastery integrity verified.');
